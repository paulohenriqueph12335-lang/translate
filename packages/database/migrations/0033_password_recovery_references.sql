-- Recuperação de senha (pedido do produto, 2026-10-28): quem esqueceu pede uma senha nova; o Diretor autoriza de vez,
-- com o Token do Diretor; o Líder libera por 24 horas, com o Token do Líder, até 3 vezes seguidas.
ALTER TABLE users ADD COLUMN access_expires_at timestamptz;
ALTER TABLE users ADD COLUMN leader_unlocks smallint NOT NULL DEFAULT 0 CHECK (leader_unlocks BETWEEN 0 AND 3);

CREATE TABLE password_reset_requests (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES users (id),
  -- Hash da senha pedida; sai quando o pedido é decidido.
  password_hash text,
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected', 'superseded')),
  created_at timestamptz NOT NULL DEFAULT now(),
  decided_at timestamptz,
  decided_by uuid REFERENCES users (id),
  decided_as text CHECK (decided_as IN ('director', 'leader')),
  access_until timestamptz,
  CHECK ((status = 'pending') = (password_hash IS NOT NULL))
);
CREATE UNIQUE INDEX password_reset_requests_pending_idx ON password_reset_requests (user_id) WHERE status = 'pending';
CREATE INDEX password_reset_requests_created_idx ON password_reset_requests (created_at DESC);

-- Referência sequencial de cada tradução: dá nome ao arquivo no ZIP quando não há número nem protocolo e serve para
-- buscar depois ("Tradução 123").
ALTER TABLE translation_jobs ADD COLUMN reference_number bigint GENERATED BY DEFAULT AS IDENTITY;
CREATE UNIQUE INDEX translation_jobs_reference_idx ON translation_jobs (reference_number);

